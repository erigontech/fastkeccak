//go:build ignore

// gen_keccakf_avx512.go generates keccakf_amd64_avx512.s, an AVX-512VL
// Keccak-f[1600] permutation that keeps one lane per xmm register (low
// quadword), like Nethermind's KeccakF1600Avx512VL. VPTERNLOGQ fuses theta's
// three-input XORs and VPROLQ does rho; pi only renames registers, so the
// generator tracks which register holds each lane and emits moves only where
// the one-round loop body must end with the mapping it started with.
//
// Usage: go run gen_keccakf_avx512.go

package main

import (
	"fmt"
	"maps"
	"os"
	"slices"
)

var rc = [24]uint64{
	0x0000000000000001, 0x0000000000008082,
	0x800000000000808a, 0x8000000080008000,
	0x000000000000808b, 0x0000000080000001,
	0x8000000080008081, 0x8000000000008009,
	0x000000000000008a, 0x0000000000000088,
	0x0000000080008009, 0x000000008000000a,
	0x000000008000808b, 0x800000000000008b,
	0x8000000000008089, 0x8000000000008003,
	0x8000000000008002, 0x8000000000000080,
	0x000000000000800a, 0x800000008000000a,
	0x8000000080008081, 0x8000000000008080,
	0x0000000080000001, 0x8000000080008008,
}

const (
	xor3      = 0x96 // a ^ b ^ c
	rateLanes = 17
)

// rho[x+5y] is the rotation of lane (x, y), from the (x, y) walk in FIPS 202 3.2.2.
var rho [25]int

func init() {
	x, y := 1, 0
	for t := 0; t < 24; t++ {
		rho[x+5*y] = ((t + 1) * (t + 2) / 2) % 64
		x, y = y, (2*x+3*y)%5
	}
}

type gen struct {
	reg  [25]int // reg[i] is the X register holding lane i
	free []int
}

var p func(string, ...any)

func x(r int) string { return fmt.Sprintf("X%d", r) }

func (g *gen) alloc() int {
	r := g.free[len(g.free)-1]
	g.free = g.free[:len(g.free)-1]
	return r
}

func (g *gen) release(r int) { g.free = append(g.free, r) }

func (g *gen) round() {
	a := &g.reg

	// Theta.
	var c [5]int
	for i := range 5 {
		c[i] = g.alloc()
		p("\tVMOVDQA64 %s, %s", x(a[i]), x(c[i]))
		p("\tVPTERNLOGQ $0x%02x, %s, %s, %s", xor3, x(a[i+10]), x(a[i+5]), x(c[i]))
		p("\tVPTERNLOGQ $0x%02x, %s, %s, %s", xor3, x(a[i+20]), x(a[i+15]), x(c[i]))
	}
	for i := range 5 {
		d := g.alloc()
		p("\tVPROLQ $1, %s, %s", x(c[(i+1)%5]), x(d))
		for y := range 5 {
			p("\tVPTERNLOGQ $0x%02x, %s, %s, %s", xor3, x(d), x(c[(i+4)%5]), x(a[i+5*y]))
		}
		g.release(d)
	}
	for _, r := range c {
		g.release(r)
	}

	// Rho in place, pi by renaming: B[y, 2x+3y] = ROL(A[x, y], rho[x, y]).
	var b [25]int
	for y := range 5 {
		for i := range 5 {
			r := a[i+5*y]
			if rho[i+5*y] != 0 {
				p("\tVPROLQ $%d, %s, %s", rho[i+5*y], x(r), x(r))
			}
			b[y+5*((2*i+3*y)%5)] = r
		}
	}
	*a = b

	// Chi with VPANDNQ+VPXORQ into fresh registers: on Zen 4 this beats
	// VPTERNLOGQ in place, whose first two outputs per row need copies.
	for y := range 5 {
		var t [5]int
		for i := range 5 {
			t[i] = g.alloc()
			p("\tVPANDNQ %s, %s, %s", x(a[5*y+(i+2)%5]), x(a[5*y+(i+1)%5]), x(t[i]))
			p("\tVPXORQ %s, %s, %s", x(a[5*y+i]), x(t[i]), x(t[i]))
		}
		for i := range 5 {
			g.release(a[5*y+i])
			a[5*y+i] = t[i]
		}
	}

	// Iota.
	p("\tVPXORQ.BCST (R13), %s, %s", x(a[0]), x(a[0]))
}

// restore emits moves that put lane i back into register want[i].
func (g *gen) restore(want [25]int) {
	src := map[int]int{} // destination register -> source register
	for i := range 25 {
		if g.reg[i] != want[i] {
			src[want[i]] = g.reg[i]
		}
	}
	isSrc := func(r int) bool {
		for _, s := range src {
			if s == r {
				return true
			}
		}
		return false
	}
	var spare []int // registers neither read nor written by the pending moves
	for r := range 32 {
		if !slices.Contains(want[:], r) && !slices.Contains(g.reg[:], r) {
			spare = append(spare, r)
		}
	}
	for len(src) > 0 {
		dsts := slices.Sorted(maps.Keys(src))
		progress := false
		for _, dst := range dsts {
			if isSrc(dst) {
				continue
			}
			p("\tVMOVDQA64 %s, %s", x(src[dst]), x(dst))
			delete(src, dst)
			progress = true
		}
		if progress {
			continue
		}
		// Only cycles are left: park one destination's value in a free register.
		dst, t := dsts[0], spare[0]
		spare = spare[1:]
		p("\tVMOVDQA64 %s, %s", x(dst), x(t))
		for d, s := range src {
			if s == dst {
				src[d] = t
			}
		}
	}
	g.reg = want
	g.free = g.free[:0]
	for r := 31; r >= 0; r-- {
		if !slices.Contains(want[:], r) {
			g.free = append(g.free, r)
		}
	}
}

func main() {
	f, err := os.Create("keccakf_amd64_avx512.s")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	p = func(format string, args ...any) { fmt.Fprintf(f, format+"\n", args...) }

	g := &gen{}
	for i := range 25 {
		g.reg[i] = i
	}
	for r := 31; r >= 25; r-- {
		g.free = append(g.free, r)
	}
	start := g.reg

	p("// Code generated by gen_keccakf_avx512.go. DO NOT EDIT.")
	p("")
	p("//go:build amd64 && !purego")
	p("")
	p("#include \"textflag.h\"")
	p("")
	p("// func keccakF1600AVX512(a *[200]byte, buf *byte)")
	// The frame is unused; it keeps the stack check, see TestKernelKeepsStackCheck.
	p("TEXT ·keccakF1600AVX512(SB), $128-16")
	p("\tMOVQ a+0(FP), DI")
	p("\tMOVQ buf+8(FP), BX")
	p("\tTESTQ BX, BX")
	p("\tJZ load")
	p("")
	for i := range 25 {
		p("\tVMOVQ %d(DI), %s", 8*i, x(i))
		if i < rateLanes {
			p("\tVPXORQ.BCST %d(BX), %s, %s", 8*i, x(i), x(i))
		}
	}
	p("\tJMP rounds")
	p("")
	p("load:")
	for i := range 25 {
		p("\tVMOVQ %d(DI), %s", 8*i, x(i))
	}
	p("")
	p("rounds:")
	p("\tLEAQ keccakAVX512RC<>(SB), R13")
	p("\tLEAQ keccakAVX512RC<>+%d(SB), R12", 8*len(rc))
	p("")
	p("loop:")
	g.round()
	g.restore(start)
	p("\tADDQ $8, R13")
	p("\tCMPQ R13, R12")
	p("\tJNE loop")
	p("")
	for i := range 25 {
		p("\tVMOVQ %s, %d(DI)", x(g.reg[i]), 8*i)
	}
	p("\tVZEROUPPER")
	p("\tRET")
	p("")
	for i, v := range rc {
		p("DATA keccakAVX512RC<>+%d(SB)/8, $0x%016x", 8*i, v)
	}
	p("GLOBL keccakAVX512RC<>(SB), RODATA|NOPTR, $%d", 8*len(rc))
}
