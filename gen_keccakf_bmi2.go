//go:build ignore

// gen_keccakf_bmi2.go generates keccakf_amd64_bmi2.s — a BMI2-optimized
// Keccak-f[1600] permutation using RORXQ and ANDNQ.
// A loop of 12 iterations, 2 rounds each, keeps the code small enough
// for the decoded-instruction cache.
//
// Key optimizations:
//   - Theta column parities are accumulated in registers while chi stores
//     the round output, so theta never reloads the state
//   - D values in registers, except two kept in the stack frame
//   - State alternates between the original array (DI) and a 200-byte stack
//     buffer, avoiding a second 200-byte copy
//   - Optional XOR-and-permute: when buf != nil, XORs rate bytes into state
//     before permuting, eliminating one full memory pass
//
// Usage: go generate (runs this generator, then asmfmt on its output)

package main

import (
	"fmt"
	"os"
	"strings"
)

var rc = [24]uint64{
	0x0000000000000001, 0x0000000000008082,
	0x800000000000808a, 0x8000000080008000,
	0x000000000000808b, 0x0000000080000001,
	0x8000000080008081, 0x8000000000008009,
	0x000000000000008a, 0x0000000000000088,
	0x0000000080008009, 0x000000008000000a,
	0x000000008000808b, 0x800000000000008b,
	0x8000000000008089, 0x8000000000008003,
	0x8000000000008002, 0x8000000000000080,
	0x000000000000800a, 0x800000008000000a,
	0x8000000080008081, 0x8000000000008080,
	0x0000000080000001, 0x8000000080008008,
}

type lane struct {
	idx int // state lane index (0–24)
	rot int // left-rotation amount
}

// Chi groups: each group reads 5 lanes (after theta+rho+pi)
// and produces 5 consecutive output lanes.
var groups = [5][5]lane{
	{{0, 0}, {6, 44}, {12, 43}, {18, 21}, {24, 14}},  // → lanes 0–4
	{{3, 28}, {9, 20}, {10, 3}, {16, 45}, {22, 61}},  // → lanes 5–9
	{{1, 1}, {7, 6}, {13, 25}, {19, 8}, {20, 18}},    // → lanes 10–14
	{{4, 27}, {5, 36}, {11, 10}, {17, 15}, {23, 56}}, // → lanes 15–19
	{{2, 62}, {8, 55}, {14, 39}, {15, 41}, {21, 2}},  // → lanes 20–24
}

// Register plan. All 15 general-purpose registers are in use in the loop:
// DI holds the array pointer, AX is the scratch register.
var (
	// Column parities of the round input, also the accumulators of the
	// column parities of the round output.
	cReg = [5]string{"BX", "CX", "DX", "SI", "BP"}
	// D values indexed by column. The last two are kept in the stack frame
	// for groups 1–4. Group 0 runs right after theta, and a reload there
	// would wait for the store just before it, so it reads them from
	// registers that are free until its chi: AX and cReg[1], which is no
	// longer needed once D[4], the last D, is computed.
	dLoc  = [5]string{"R13", "R14", "R15", fmt.Sprintf("%d(SP)", dSlot), fmt.Sprintf("%d(SP)", dSlot+8)}
	dLoc0 = [5]string{"R13", "R14", "R15", "AX", cReg[1]}
	// Theta+rho+pi output lanes of a chi group.
	bReg = [5]string{"R8", "R9", "R10", "R11", "R12"}
)

// keptLane stays in bReg[4] between rounds: the last chi group computes it
// and group 0 of the next round reads it right after theta, so a reload would
// wait for its store, as for dLoc. It must be 24, the lane at position 4 of
// both groups.
const keptLane = 24

// Frame layout: 25 lane slots of temp state, then 8-byte slots. keptLane is
// the last lane and its slot is never used, so the 8-byte slots start there.
const (
	rcPtr     = keptLane * 8 // pointer to the round constants of the current even round
	rcEnd     = rcPtr + 8    // end of the round constants table
	dSlot     = rcEnd + 8    // D[3], D[4]
	fsize     = dSlot + 16
	rateLanes = 17 // rate / 8 = 136 / 8
)

var asm strings.Builder

func p(format string, args ...any) { fmt.Fprintf(&asm, format+"\n", args...) }

func main() {
	p("// Code generated by gen_keccakf_bmi2.go. DO NOT EDIT.")
	p("")
	p("//go:build amd64 && !purego")
	p("")
	p("#include \"textflag.h\"")
	p("")
	for i, c := range rc {
		p("DATA rc<>+%d(SB)/8, $0x%016x", i*8, c)
	}
	p("GLOBL rc<>(SB), RODATA|NOPTR, $%d", len(rc)*8)
	p("")

	// Single function: keccakF1600BMI2(a *[200]byte, buf *byte)
	// When buf != nil, XORs rate bytes into state before permuting.
	// When buf == nil, just permutes.
	// Do NOT add NOSPLIT here, and do not shrink the frame below 128 bytes.
	// The frame holds the round temp state, and its stack check is the only
	// preemption point in the callers' block loops: assembly is not
	// async-preemptible, so without it a large Sum256 or Write holds every P
	// in stop-the-world until it finishes. The arm64 kernel omits NOSPLIT for
	// the same reason.
	p("// func keccakF1600BMI2(a *[200]byte, buf *byte)")
	p("TEXT ·keccakF1600BMI2(SB), $%d-16", fsize)
	p("\tMOVQ a+0(FP), DI")
	p("\tMOVQ buf+8(FP), BX")
	p("\tTESTQ BX, BX")
	p("\tJZ rounds")
	p("")
	p("\t// XOR %d lanes (%d bytes) of buf into state.", rateLanes, rateLanes*8)
	for i := 0; i < rateLanes; i++ {
		p("\tMOVQ %d(BX), AX", i*8)
		p("\tXORQ AX, %d(DI)", i*8)
	}
	p("")
	p("rounds:")
	p("\tLEAQ rc<>(SB), AX")
	p("\tMOVQ AX, %d(SP)", rcPtr)
	p("\tADDQ $%d, AX", len(rc)*8)
	p("\tMOVQ AX, %d(SP)", rcEnd)
	p("")
	p("\t// Column parities of the initial state.")
	for c := 0; c < 5; c++ {
		p("\tMOVQ %s, %s", off(c, "DI"), cReg[c])
		for r := 1; r < 5; r++ {
			p("\tXORQ %s, %s", off(r*5+c, "DI"), cReg[c])
		}
	}
	p("\tMOVQ %s, %s", off(keptLane, "DI"), bReg[4])
	p("")
	p("loop:")
	p("\t// Even round: array -> stack.")
	emitRound("DI", "SP", 0)
	p("")
	p("\t// Odd round: stack -> array.")
	emitRound("SP", "DI", 8)
	p("")
	p("\tMOVQ %d(SP), AX", rcPtr)
	p("\tADDQ $16, AX")
	p("\tMOVQ AX, %d(SP)", rcPtr)
	p("\tCMPQ AX, %d(SP)", rcEnd)
	p("\tJNE loop")
	p("\tMOVQ %s, %s", bReg[4], off(keptLane, "DI"))
	p("\tRET")

	if err := os.WriteFile("keccakf_amd64_bmi2.s", []byte(asm.String()), 0o644); err != nil {
		panic(err)
	}
}

// emitRound emits one round from the state at base register src to dst, with
// the round constant at rcOff from rcPtr. cReg hold the column parities of
// the input on entry and of the output on exit.
func emitRound(src, dst string, rcOff int) {
	// D[x] = C[(x+4)%5] ^ rol(C[(x+1)%5], 1).
	for x := 0; x < 5; x++ {
		p("\tRORXQ $63, %s, %s", cReg[(x+1)%5], dLoc0[x])
		p("\tXORQ %s, %s", cReg[(x+4)%5], dLoc0[x])
		if dLoc[x] != dLoc0[x] {
			p("\tMOVQ %s, %s", dLoc0[x], dLoc[x])
		}
	}

	for g := 0; g < 5; g++ {
		emitChi(g, src, dst, rcOff)
	}
}

// emitChi emits theta+rho+pi and chi for one group of 5 output lanes.
// The first group initializes the column parity accumulators cReg, and the
// others XOR into them.
func emitChi(g int, src, dst string, rcOff int) {
	d := dLoc
	if g == 0 {
		d = dLoc0
	}
	for i, l := range groups[g] {
		if l.idx != keptLane {
			p("\tMOVQ %s, %s", off(l.idx, src), bReg[i])
		}
		p("\tXORQ %s, %s", d[l.idx%5], bReg[i])
		if l.rot != 0 {
			p("\tRORXQ $%d, %s, %s", 64-l.rot, bReg[i], bReg[i])
		}
	}

	// Chi: out[j] = B[j] ^ (~B[(j+1)%5] & B[(j+2)%5]). Starting with outputs
	// 2 and 3, which read the last two B values, is a measured scheduling
	// choice: the natural order is slower.
	for _, j := range []int{2, 3, 4, 1, 0} {
		out := "AX"
		if g == 0 {
			out = cReg[j]
		}
		p("\tANDNQ %s, %s, %s", bReg[(j+2)%5], bReg[(j+1)%5], out)
		if g*5+j == keptLane {
			// In place: outputs 2 and 3, the other readers of B[4], are done.
			p("\tXORQ %s, %s", out, bReg[4])
			p("\tXORQ %s, %s", bReg[4], cReg[j])
			continue
		}
		p("\tXORQ %s, %s", bReg[j], out)
		if g == 0 && j == 0 {
			// Iota. AX held D[3] only for this group's theta.
			p("\tMOVQ %d(SP), AX", rcPtr)
			p("\tXORQ %d(AX), %s", rcOff, out)
		}
		p("\tMOVQ %s, %s", out, off(g*5+j, dst))
		if g != 0 {
			p("\tXORQ AX, %s", cReg[j])
		}
	}
}

// off returns the memory operand for lane idx of the state at base register base.
func off(idx int, base string) string {
	return fmt.Sprintf("%d(%s)", idx*8, base)
}
